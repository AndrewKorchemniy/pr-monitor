//! Build metadata, the embedded license notices, the icon (the theme's brand mark) and the
//! Windows resources (icon, version info, manifest).
#![allow(
    clippy::print_stdout,
    reason = "cargo reads build-script directives from stdout"
)]

use std::{
    env,
    error::Error,
    fs,
    path::{Path, PathBuf},
};

use prm_domain::app::{APP_DISPLAY_NAME, APP_EXE_NAME, APP_ID};

#[path = "build/icon_gen.rs"]
mod icon_gen;

const ICO_SIZES: [u32; 8] = [16, 20, 24, 32, 40, 48, 64, 256];
const LICENSES_PLACEHOLDER: &str = "Third-party notices are embedded in release builds.\n\
See THIRD-PARTY-LICENSES.html in the release archive.\n";

fn main() -> Result<(), Box<dyn Error>> {
    for p in ["build.rs", "build/icon_gen.rs", "assets"] {
        println!("cargo:rerun-if-changed={p}");
    }
    println!("cargo:rerun-if-env-changed=PRM_BUILD_SHA");
    println!("cargo:rerun-if-env-changed=PRM_THIRD_PARTY_LICENSES");
    let out = PathBuf::from(env::var_os("OUT_DIR").ok_or("OUT_DIR")?);
    let assets = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").ok_or("CARGO_MANIFEST_DIR")?)
        .join("assets");
    metadata()?;
    notices(&out)?;
    let ico = icons(&assets, &out)?;
    // why: build scripts run on the host, so check the target, not cfg!(windows).
    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        resources(&assets, &ico)?;
    }
    Ok(())
}

fn metadata() -> Result<(), Box<dyn Error>> {
    let sha = env::var("PRM_BUILD_SHA")
        .ok()
        .map(|s| s.trim().chars().take(12).collect::<String>())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "dev".to_owned());
    println!("cargo:rustc-env=PRM_BUILD_SHA={sha}");
    println!("cargo:rustc-env=PRM_TARGET={}", env::var("TARGET")?);
    Ok(())
}

/// `$PRM_THIRD_PARTY_LICENSES` (cargo-about's text output) or a placeholder.
fn notices(out: &Path) -> Result<(), Box<dyn Error>> {
    let notices = out.join("THIRD-PARTY-LICENSES.txt");
    match env::var_os("PRM_THIRD_PARTY_LICENSES") {
        Some(p) => {
            println!("cargo:rerun-if-changed={}", PathBuf::from(&p).display());
            fs::copy(&p, &notices)?;
        }
        None => fs::write(&notices, LICENSES_PLACEHOLDER)?,
    }
    Ok(())
}

/// The mark in graphite with the idle bar; `assets/{icon-256.png,app.ico}` override it.
fn icons(assets: &Path, out: &Path) -> Result<PathBuf, Box<dyn Error>> {
    let registry = prm_theme::ThemeRegistry::builtin();
    let (tokens, _) = registry
        .tokens(
            prm_theme::registry::DEFAULT_DARK,
            prm_theme::Density::Compact,
        )
        .ok_or("the built-in dark theme is missing")?;
    let palette = &tokens.palette;
    let colors = prm_theme::MarkColors::from_palette(palette, palette.signature_revision);
    let render = |size| prm_theme::render_mark(size, &colors);
    let png = pick(
        &assets.join("icon-256.png"),
        &out.join("icon-256.png"),
        || icon_gen::png(&render(256), 256),
    )?;
    println!("cargo:rustc-env=PRM_ICON_256_PNG={}", png.display());
    pick(&assets.join("app.ico"), &out.join("app.ico"), || {
        let images: Vec<_> = ICO_SIZES
            .iter()
            .map(|&size| icon_gen::IcoImage {
                size,
                rgba: render(size),
            })
            .collect();
        icon_gen::ico(&images)
    })
}

/// An override file when present, else the generated bytes written to `generated`.
fn pick(
    override_path: &Path,
    generated: &Path,
    make: impl FnOnce() -> Result<Vec<u8>, Box<dyn Error>>,
) -> Result<PathBuf, Box<dyn Error>> {
    if override_path.is_file() {
        return Ok(override_path.to_path_buf());
    }
    fs::write(generated, make()?)?;
    Ok(generated.to_path_buf())
}

fn resources(assets: &Path, ico: &Path) -> Result<(), Box<dyn Error>> {
    let mut res = winresource::WindowsResource::new();
    res.set_icon(ico.to_str().ok_or("non-UTF-8 path")?)
        .set_manifest_file(
            assets
                .join("app.manifest")
                .to_str()
                .ok_or("non-UTF-8 path")?,
        )
        .set("ProductName", APP_DISPLAY_NAME)
        .set("FileDescription", APP_DISPLAY_NAME)
        .set("CompanyName", "Andrew Korchemniy")
        .set("OriginalFilename", APP_EXE_NAME)
        .set("InternalName", APP_ID)
        .set(
            "LegalCopyright",
            "Copyright (c) Andrew Korchemniy. MIT OR Apache-2.0",
        );
    res.compile()?;
    Ok(())
}
